#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	char	*dst;
	int		len1;
	int		len2;

	len1 = ft_strlen(s1);
	len2 = ft_strlen(s2);
	dst = (char *)malloc(len1 + len2 + 1);
	if (!dst)
		return (NULL);
	ft_memmove(dst, s1, len1);
	ft_memmove(dst + len1, s2, len2 + 1);
	return (dst);
}

